/** Replace {name} placeholders. A placeholder without a value stays as it is. */
function fill(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (Object.hasOwn(params, name) ? String(params[name]) : whole));
}

/** Text for a key (interface text or code) in a language. Unknown key: the key itself. */
export function translate(lang, key, params) {
  const table = MESSAGES[lang] || MESSAGES[DEFAULT_LANGUAGE];
  const text = Object.hasOwn(table, key) ? table[key] : undefined;
  return text === undefined ? key : fill(text, params);
}

/** Text for a code (E_, I_, W_, APP_) in a language. Unknown code: the code itself. */
export const codeText = translate;

/** First language from the browser language: starts with "de" -> German, otherwise English. */
export function detectLanguage(navigatorLanguage) {
  return typeof navigatorLanguage === 'string' && navigatorLanguage.trim().toLowerCase().startsWith('de') ? 'de' : 'en';
}

function readStorage(storage, key) {
  try {
    return storage ? storage.getItem(key) : null;
  } catch {
    return null;
  }
}

/** Language to start with: the stored choice, else derived from the browser language. */
export function loadLanguage(storage, navigatorLanguage) {
  const stored = readStorage(storage, LANGUAGE_STORAGE_KEY);
  return LANGUAGES.includes(stored) ? stored : detectLanguage(navigatorLanguage);
}

/** Remember the language choice (only the language, never a model). */
export function saveLanguage(storage, lang) {
  if (!LANGUAGES.includes(lang)) return;
  try {
    if (storage) storage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // storage may be unavailable (private mode); the choice then lasts for the session only
  }
}
